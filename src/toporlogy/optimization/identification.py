"""Parameter identification (inverse problem): weighted least squares with optional Gaussian prior (Tikhonov),
identifiability from the SVD of the weighted Jacobian, multi-start and held-out validation.

Residuals: r_i = (m_i(θ) − y_i) / σ_i, plus (θ_j − p_j) / s_j for a prior. The solver is SciPy
``least_squares`` (trust-region reflective, bounds) in scaled coordinates q = θ / scale. The Jacobian is the caller's
analytic one or central differences; check an analytic one with :func:`verify_model_jacobian`.

Identifiability (data only, prior excluded): J = ∂r/∂q at the estimate, SVD J = U Σ Vᵀ. ``rank`` counts
σ_i > rank_rtol σ_max; the rows of Vᵀ beyond it (``null_space``, columns, in q coordinates) are parameter
directions the data does not see. This is local (at the estimate) and practical, not a structural proof. The
covariance (JᵀJ)⁻¹ (prior rows included when a prior is given) assumes the stated σ are correct and the model is
right; it is None when that matrix is rank deficient. A good fit of the training data says nothing about model error:
use :func:`weighted_rms` on held-out data.

:class:`Observations` must say whether the numbers are ``"synthetic"`` (generated by a model) or ``"measured"``;
the two are never mixed silently.

Verification: ``tests/toporlogy/test_identification.py`` (records I1-I7 of
``docs/olcumler/laminat_uq_onkayit.md``).
"""
from __future__ import annotations

import math
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from typing import Any

import numpy as np
from scipy.optimize import least_squares
from scipy.stats import qmc

__all__ = ["Observations", "GaussianPrior", "Identification", "central_jacobian", "verify_model_jacobian", "identify",
           "multi_start_identify", "weighted_rms", "DATA_KINDS", "RANK_RTOL"]

DATA_KINDS = ("synthetic", "measured")
RANK_RTOL = 1e-8


@dataclass(frozen=True)
class Observations:
    """Measured (or synthetic) responses ``values`` (m,) with standard deviations ``sigma`` (m,)."""

    values: np.ndarray
    sigma: np.ndarray
    kind: str
    description: str = ""

    def __post_init__(self) -> None:
        y = np.asarray(self.values, float).reshape(-1)
        s = np.broadcast_to(np.asarray(self.sigma, float), y.shape).copy()
        if y.size == 0 or not np.isfinite(y).all():
            raise ValueError("observations must be finite and non-empty")
        if not (np.isfinite(s).all() and (s > 0).all()):
            raise ValueError("every observation needs a positive sigma")
        if self.kind not in DATA_KINDS:
            raise ValueError(f"kind: one of {DATA_KINDS}")
        object.__setattr__(self, "values", y)
        object.__setattr__(self, "sigma", s)


@dataclass(frozen=True)
class GaussianPrior:
    mean: np.ndarray
    std: np.ndarray


@dataclass(frozen=True)
class Identification:
    """``theta`` estimate; ``weighted_rms`` of the data residuals; SVD summary of module notes; ``covariance`` /
    ``std`` in parameter units (None when not defined)."""

    names: tuple[str, ...]
    theta: np.ndarray
    cost: float
    weighted_rms: float
    singular_values: np.ndarray
    rank: int
    condition: float
    null_space: np.ndarray
    covariance: np.ndarray | None
    std: np.ndarray | None
    success: bool
    n_evaluations: int
    kind: str

    @property
    def identifiable(self) -> bool:
        return self.rank == len(self.names)


Model = Callable[[np.ndarray], np.ndarray]


def central_jacobian(model: Model, theta: Any, scale: Any, rel_step: float = 1e-6) -> np.ndarray:
    """∂model/∂θ (m, p) by central differences with steps rel_step · scale."""
    t = np.asarray(theta, float)
    h = rel_step * np.broadcast_to(np.asarray(scale, float), t.shape)
    cols = []
    for j in range(t.size):
        e = np.zeros_like(t)
        e[j] = h[j]
        cols.append((np.asarray(model(t + e), float) - np.asarray(model(t - e), float)) / (2 * h[j]))
    return np.column_stack(cols)


def verify_model_jacobian(model: Model, jacobian: Model, theta: Any, scale: Any) -> float:
    """max |J − J_fd| (columns scaled by ``scale``) over max |J_fd| (scaled)."""
    s = np.asarray(scale, float)
    ja = np.asarray(jacobian(np.asarray(theta, float)), float) * s
    fd = central_jacobian(model, theta, scale) * s
    if ja.shape != fd.shape:
        raise ValueError(f"jacobian has shape {ja.shape}, the model gives {fd.shape}")
    return float(np.abs(ja - fd).max() / max(np.abs(fd).max(), 1e-300))


def identify(model: Model, observations: Observations, theta0: Any, bounds: tuple[Any, Any],
             names: Sequence[str], jacobian: Model | None = None, scale: Any = None,
             prior: GaussianPrior | None = None, rank_rtol: float = RANK_RTOL) -> Identification:
    """Estimate θ (p,) from ``observations`` (module notes). ``scale`` (p,): typical magnitudes (default |θ0|, 1 for
    zero entries)."""
    t0 = np.asarray(theta0, float).reshape(-1)
    p = t0.size
    if len(names) != p:
        raise ValueError(f"{len(names)} names for {p} parameters")
    lo, hi = (np.broadcast_to(np.asarray(b, float), (p,)) for b in bounds)
    if not ((lo < hi).all() and (t0 >= lo).all() and (t0 <= hi).all()):
        raise ValueError("bounds need low < high and theta0 inside them")
    s = np.where(t0 != 0, np.abs(t0), 1.0) if scale is None else np.broadcast_to(np.asarray(scale, float), (p,))
    if not (s > 0).all():
        raise ValueError("scales must be positive")
    y, sig = observations.values, observations.sigma
    if prior is not None:
        pm, ps = np.asarray(prior.mean, float).reshape(p), np.asarray(prior.std, float).reshape(p)
        if not (ps > 0).all():
            raise ValueError("prior std must be positive (use a large value for a weak prior)")

    def predict(theta: np.ndarray) -> np.ndarray:
        out = np.asarray(model(theta), float).reshape(-1)
        if out.shape != y.shape:
            raise ValueError(f"the model returns {out.size} values for {y.size} observations")
        return out

    def data_jacobian(theta: np.ndarray) -> np.ndarray:
        J = central_jacobian(predict, theta, s) if jacobian is None else np.asarray(jacobian(theta), float)
        return J * s / sig[:, None]                                       # ∂r/∂q

    def residual(q: np.ndarray) -> np.ndarray:
        theta = q * s
        r = (predict(theta) - y) / sig
        return r if prior is None else np.concatenate([r, (theta - pm) / ps])

    def jac(q: np.ndarray) -> np.ndarray:
        J = data_jacobian(q * s)
        return J if prior is None else np.vstack([J, np.diag(s / ps)])

    sol = least_squares(residual, t0 / s, jac=jac, bounds=(lo / s, hi / s), method="trf", ftol=1e-15, xtol=1e-15,
                        gtol=1e-12, max_nfev=500)
    theta = sol.x * s
    J = data_jacobian(theta)
    _, sv, Vt = np.linalg.svd(J, full_matrices=True)
    sv_full = np.concatenate([sv, np.zeros(p - sv.size)])
    smax = float(sv_full.max(initial=0.0))
    rank = int((sv_full > rank_rtol * smax).sum()) if smax > 0 else 0
    cond = float(smax / sv_full.min()) if sv_full.min() > 0 else math.inf
    H = jac(sol.x)
    hs = np.linalg.svd(H, compute_uv=False)
    cov = std = None
    if H.shape[0] >= p and hs.min() > rank_rtol * hs.max():
        pinv = np.linalg.pinv(H)
        cov = (pinv @ pinv.T) * np.outer(s, s)
        std = np.sqrt(np.diag(cov))
    r = (predict(theta) - y) / sig
    return Identification(tuple(names), theta, float(sol.cost), float(math.sqrt(np.mean(r ** 2))), sv_full, rank,
                          cond, Vt[rank:].T.copy(), cov, std, bool(sol.success), int(sol.nfev), observations.kind)


def multi_start_identify(model: Model, observations: Observations, bounds: tuple[Any, Any], names: Sequence[str],
                         n_starts: int = 16, seed: int = 0, agree_rtol: float = 1e-6,
                         **kwargs: Any) -> tuple[list[Identification], int]:
    """:func:`identify` from a Latin hypercube of starts inside ``bounds``: (results sorted by cost, number of
    results whose θ equals the best one to ``agree_rtol`` of the scale). A failed start raises."""
    p = len(names)
    lo, hi = (np.broadcast_to(np.asarray(b, float), (p,)) for b in bounds)
    if not (np.isfinite(lo).all() and np.isfinite(hi).all()):
        raise ValueError("multi-start needs finite bounds")
    starts = lo + (hi - lo) * qmc.LatinHypercube(p, seed=seed).random(n_starts)
    kwargs.setdefault("scale", 0.5 * (np.abs(lo) + np.abs(hi)))
    runs = sorted((identify(model, observations, t0, (lo, hi), names, **kwargs) for t0 in starts),
                  key=lambda r: r.cost)
    s = np.asarray(kwargs["scale"], float)
    agree = sum(bool(np.max(np.abs(r.theta - runs[0].theta) / s) <= agree_rtol) for r in runs)
    return runs, int(agree)


def weighted_rms(model: Model, observations: Observations, theta: Any) -> float:
    """√mean(((m(θ) − y) / σ)²): about 1 when model and noise level are right, large under model mismatch."""
    out = np.asarray(model(np.asarray(theta, float)), float).reshape(-1)
    if out.shape != observations.values.shape:
        raise ValueError(f"the model returns {out.size} values for {observations.values.size} observations")
    return float(math.sqrt(np.mean(((out - observations.values) / observations.sigma) ** 2)))
